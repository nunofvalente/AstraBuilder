alter table public.game_matches
  add column if not exists game_state jsonb;

create table if not exists public.game_match_actions (
  id bigint generated by default as identity primary key,
  match_id uuid not null references public.game_matches(id) on delete cascade,
  revision integer not null,
  actor_user_id uuid not null references auth.users(id) on delete cascade,
  action jsonb not null,
  created_at timestamptz not null default now(),
  unique (match_id, revision)
);

create index if not exists game_match_actions_match_id_idx
  on public.game_match_actions (match_id, revision);

alter table public.game_match_actions enable row level security;
